"""
flatworld.topography -- the topology INPUT for Stage C: land/sea mask + altitude on a 2-D grid.

The grid is UNIFORM IN PHYSICAL DISTANCE (x cross-track [m], e along-track [m]); latitude theta is the
derived quantity theta = arctan(x / L). Three ways to make a topology:

  * Topography.procedural_continent(seed, ...) -- a procedurally generated landmass (fractal coastline +
    ridged interior mountains + coastal taper), the reproducible stand-in used to sample many
    continents. Orientation, width, and along/cross-track placement are controllable. This is the
    DEFAULT the cascade uses when no topology is supplied.
  * Topography.from_arrays(x, e, land, height) -- wrap (and validate) an arbitrary externally supplied
    topology, e.g. one produced by a separate geophysics model. Feed the result straight into the
    cascade (run_cascade(..., topo=...)) to compute the climate that topology generates.
  * Topography.load(path) / TopoGrid.save(path) -- the on-disk handoff (an .npz of x/e/land/height)
    for that external topology, so another model can write a file and the cascade can read it.

Box-size independence (a documented hazard: shallow continental belts that run off the domain edge
self-starve of sea moisture) is supported by making the along-track extent ``Le`` and the cross-track
span explicit and testable.
"""
from __future__ import annotations
import numpy as np
import scipy.ndimage as ndi
from dataclasses import dataclass
from . import geometry as g


@dataclass
class TopoGrid:
    x: np.ndarray            # cross-track cell-center distances [m] (shape nx)
    e: np.ndarray            # along-track cell-center distances [m] (shape ne)
    land: np.ndarray         # boolean land mask (nx, ne)
    height: np.ndarray       # altitude [m] (nx, ne), 0 over sea
    meta: dict

    @property
    def theta_deg(self):
        return np.degrees(g.theta_of_x(self.x))

    @property
    def dx(self):
        return float(self.x[1] - self.x[0])

    @property
    def de(self):
        return float(self.e[1] - self.e[0])

    def distance_to_coast_km(self):
        """Euclidean distance from each land cell to the nearest sea cell [km] (continentality)."""
        if not self.land.any():
            return np.zeros_like(self.height)
        # anisotropic spacing: scale both axes to km
        d = ndi.distance_transform_edt(self.land, sampling=[self.dx / 1e3, self.de / 1e3])
        return d

    def validate(self, rtol=1e-6):
        """Check an (externally supplied) topology against the grid assumptions Stage C relies on, and
        return self so it can be used inline. Stage C reads a SINGLE dx/de from the first cell interval
        (TopoGrid.dx/de) and grids/reasons in physical distance, so the coordinates must be 1-D, the
        land/height fields must be (nx, ne), and x/e must be UNIFORMLY spaced and increasing -- a
        non-uniform grid would silently mis-scale every gradient, divergence, and coast distance."""
        x, e, land, height = self.x, self.e, self.land, self.height
        if x.ndim != 1 or e.ndim != 1:
            raise ValueError(f"x and e must be 1-D coordinate vectors (got {x.ndim}-D and {e.ndim}-D)")
        nx, ne = x.size, e.size
        if land.shape != (nx, ne) or height.shape != (nx, ne):
            raise ValueError(f"land and height must both be (nx, ne)=({nx}, {ne}); "
                             f"got land {land.shape}, height {height.shape}")
        for name, coord in (("x", x), ("e", e)):
            if coord.size < 2:
                raise ValueError(f"{name} needs at least 2 cells")
            d = np.diff(coord)
            if d[0] <= 0 or not np.all(d > 0):
                raise ValueError(f"{name} must be strictly increasing")
            if not np.allclose(d, d[0], rtol=rtol, atol=0.0):
                raise ValueError(f"{name} must be uniformly spaced in physical distance (Stage C reads "
                                 f"a single d{name}); spacing ranges {d.min():.4g}..{d.max():.4g} m")
        if not np.all(np.isfinite(height)):
            raise ValueError("height contains non-finite values")
        return self

    def save(self, path):
        """Persist this topology to an .npz (arrays x, e, land, height + the meta dict). The inverse of
        Topography.load(): the on-disk handoff for a topology generated by another model."""
        np.savez(path, x=self.x, e=self.e, land=self.land, height=self.height,
                 meta=np.array(self.meta, dtype=object))


class Topography:
    @staticmethod
    def _grid(nx, ne, x_lo, x_hi, Le):
        x = x_lo + (np.arange(nx) + 0.5) * (x_hi - x_lo) / nx
        e = (np.arange(ne) + 0.5) * Le / ne
        return x, e

    @staticmethod
    def from_arrays(x, e, land, height, meta=None, validate=True):
        """Wrap an externally supplied topology as a TopoGrid. x, e are cell-center distances [m]; land
        is a boolean (nx, ne) mask; height is altitude [m] (0 over sea, conventionally). By default the
        grid is validated (TopoGrid.validate) against Stage C's uniform-grid assumptions; pass
        validate=False to skip. meta is tagged kind='external' unless the caller overrides it."""
        topo = TopoGrid(np.asarray(x, float), np.asarray(e, float),
                        np.asarray(land, bool), np.asarray(height, float),
                        {"kind": "external", **(meta or {})})
        if validate:
            topo.validate()
        return topo

    @staticmethod
    def load(path, validate=True):
        """Load an externally generated topology from an .npz holding arrays x, e, land, height (and an
        optional meta dict) -- the read side of the geophysics-model handoff (TopoGrid.save writes it)."""
        z = np.load(path, allow_pickle=True)
        meta = z["meta"].item() if "meta" in z.files else {}
        return Topography.from_arrays(z["x"], z["e"], z["land"], z["height"],
                                      meta={"source": str(path), **(meta or {})}, validate=validate)

    @staticmethod
    def aquaplanet(nx=120, ne=120, theta_lo=30.0, theta_hi=62.0, Le_km=6000.0):
        """All-ocean reference topology spanning the hot edge through the ribbon to the frozen zone."""
        x_lo = g.x_of_theta(np.radians(theta_lo)); x_hi = g.x_of_theta(np.radians(theta_hi))
        x, e = Topography._grid(nx, ne, x_lo, x_hi, Le_km * 1e3)
        land = np.zeros((nx, ne), bool); h = np.zeros((nx, ne))
        return TopoGrid(x, e, land, h, {"kind": "aquaplanet"})

    @staticmethod
    def procedural_continent(seed=0, nx=140, ne=140, theta_lo=30.0, theta_hi=62.0, Le_km=6000.0,
                             land_fraction=0.45, mountain_height=3500.0, orient_deg=0.0,
                             center_theta=48.0, width_km=3500.0):
        """A procedural continent on a (uniform-in-distance) grid.

        fractal-noise landmass thresholded to ``land_fraction``, masked to an oriented belt of
        across-strike width ``width_km`` centered at ``center_theta``, with ridged interior mountains
        and a coastal altitude taper (no sea cliffs). Returns a TopoGrid.
        """
        rng = np.random.default_rng(seed)
        x_lo = g.x_of_theta(np.radians(theta_lo)); x_hi = g.x_of_theta(np.radians(theta_hi))
        x, e = Topography._grid(nx, ne, x_lo, x_hi, Le_km * 1e3)
        Xg, Eg = np.meshgrid(x, e, indexing="ij")                 # (nx, ne) physical distance [m]

        # --- fractal (fBm-like) field by summing smoothed white noise at octaves ---
        def fbm(shape, octaves=5):
            f = np.zeros(shape)
            for o in range(octaves):
                scale = 2.0 ** o
                n = rng.standard_normal(shape)
                f += ndi.gaussian_filter(n, sigma=max(shape[0], shape[1]) / (6 * scale)) / scale
            return (f - f.mean()) / (f.std() + 1e-9)

        base = fbm((nx, ne))
        # oriented belt mask: distance from the belt centerline (rotated coords)
        a = np.radians(orient_deg)
        xc = g.x_of_theta(np.radians(center_theta))
        # belt coordinate across the strike (perpendicular to the belt's long axis)
        across = (Xg - xc) * np.cos(a) - (Eg - Eg.mean()) * np.sin(a)
        belt = np.exp(-0.5 * (across / (0.5 * width_km * 1e3)) ** 2)
        field = base + 2.2 * (belt - 0.5)                          # bias land toward the belt
        thresh = np.quantile(field, 1.0 - land_fraction)
        land = field > thresh
        land = ndi.binary_closing(land, iterations=1)              # remove specks

        # --- altitude: ridged-multifractal mountains inland, tapered to 0 at the coast ---
        d_in = ndi.distance_transform_edt(land, sampling=[float(x[1] - x[0]) / 1e3,
                                                           float(e[1] - e[0]) / 1e3])  # km inland
        ridged = np.abs(fbm((nx, ne), octaves=6))
        ridged = 1.0 - ridged / (ridged.max() + 1e-9)              # ridge lines
        taper = np.clip(d_in / 250.0, 0.0, 1.0)                    # 0 at coast -> 1 by 250 km inland
        height = np.where(land, mountain_height * ridged * taper, 0.0)
        height = ndi.gaussian_filter(height, sigma=1.0) * land
        return TopoGrid(x, e, land, height,
                        {"kind": "procedural", "seed": seed, "orient_deg": orient_deg,
                         "center_theta": center_theta, "width_km": width_km,
                         "land_fraction": float(land.mean())})

    @staticmethod
    def tectonic_continent(seed=0, nx=300, ne=400, theta_lo=28.0, theta_hi=62.0, Le_km=12000.0, **kw):
        """A geophysics-motivated topology: a LAND/SEA mask from a synthesized linear, non-closing plate
        network -> elongated, breakup-width-capped continental belts (a RANGE of sizes), PLUS volcanic
        ISLAND CHAINS (hotspot + subduction-arc) that emerge where edifices breach the abyssal depth; and
        a HEIGHT field from a local tectonic-uplift-vs-climate-erosion equilibrium (convergent arcs /
        collision belts). The world is a NON-PERIODIC infinite plane: this builds on a domain PADDED by
        pad_km and returns the FULL padded grid, delivering the central Le_km region (meta['central_e_slice'];
        viz_topo and the cascade crop to it). Supports negative theta (both sides of the equator). The
        geology+climate-consistent alternative to procedural_continent (which is preserved). See
        flatworld.tectonics.generate for the parameters (orient_deg/center_theta/width_km/len_km/
        land_fraction/n_continents pin the S11 archetype axes; None draws them from the seed)."""
        from . import tectonics
        return tectonics.generate(seed=seed, nx=nx, ne=ne, theta_lo=theta_lo,
                                  theta_hi=theta_hi, Le_km=Le_km, **kw)
